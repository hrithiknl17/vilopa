-- Bharat Bazaar: a small Indian e-commerce schema used as mita's demo and test fixture.
--
-- Shapes on purpose, because a real erasure has to cope with them:
--   * customers.referred_by_customer_id is a self-referencing FK with NO ACTION, so
--     erasing a referrer means detaching the people they referred first.
--   * orders are kept for accounting; their customer and address links are nullable
--     so a kept order can be detached from an erased person.
--   * invoices must be retained as issued (tax records), PII included.
--   * support_tickets.customer_id is nullable: guest tickets link only by contact_email.
--   * events.customer_id has NO foreign key, like most analytics tables in the wild.
--     The data map declares that link as a relation.
--   * orders.delivery_notes and support_tickets.body are free text with phone numbers
--     and landmarks inside.

CREATE TABLE customers (
  id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email                   text NOT NULL UNIQUE,
  phone                   text,
  full_name               text NOT NULL,
  date_of_birth           date,
  pan                     text,
  referred_by_customer_id bigint REFERENCES customers (id),
  created_at              timestamptz NOT NULL,
  last_login_at           timestamptz
);

CREATE TABLE addresses (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES customers (id),
  line1       text NOT NULL,
  line2       text,
  city        text NOT NULL,
  state       text NOT NULL,
  pin_code    text NOT NULL,
  phone       text,
  is_default  boolean NOT NULL DEFAULT false
);

CREATE TABLE products (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku         text NOT NULL UNIQUE,
  name        text NOT NULL,
  price_paise bigint NOT NULL CHECK (price_paise > 0)
);

CREATE TABLE orders (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id    bigint REFERENCES customers (id),
  address_id     bigint REFERENCES addresses (id),
  status         text NOT NULL CHECK (status IN ('placed', 'shipped', 'delivered', 'cancelled')),
  total_paise    bigint NOT NULL,
  delivery_notes text,
  placed_at      timestamptz NOT NULL
);

CREATE TABLE order_items (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id         bigint NOT NULL REFERENCES orders (id),
  product_id       bigint NOT NULL REFERENCES products (id),
  quantity         int NOT NULL CHECK (quantity > 0),
  unit_price_paise bigint NOT NULL
);

CREATE TABLE invoices (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id        bigint NOT NULL UNIQUE REFERENCES orders (id),
  invoice_number  text NOT NULL UNIQUE,
  billing_name    text NOT NULL,
  billing_address text NOT NULL,
  gstin           text,
  amount_paise    bigint NOT NULL,
  issued_at       timestamptz NOT NULL
);

CREATE TABLE payments (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id     bigint NOT NULL REFERENCES orders (id),
  provider     text NOT NULL CHECK (provider IN ('upi', 'card', 'cod')),
  provider_ref text,
  upi_id       text,
  amount_paise bigint NOT NULL,
  status       text NOT NULL CHECK (status IN ('pending', 'captured', 'failed', 'refunded')),
  paid_at      timestamptz
);

CREATE TABLE reviews (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES customers (id),
  product_id  bigint NOT NULL REFERENCES products (id),
  rating      smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body        text,
  created_at  timestamptz NOT NULL
);

CREATE TABLE support_tickets (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id   bigint REFERENCES customers (id),
  contact_email text NOT NULL,
  subject       text NOT NULL,
  body          text NOT NULL,
  created_at    timestamptz NOT NULL
);

CREATE TABLE wishlists (
  customer_id bigint NOT NULL REFERENCES customers (id),
  product_id  bigint NOT NULL REFERENCES products (id),
  added_at    timestamptz NOT NULL,
  PRIMARY KEY (customer_id, product_id)
);

CREATE TABLE events (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint,  -- deliberately no FK: see header
  kind        text NOT NULL,
  properties  jsonb NOT NULL DEFAULT '{}',
  ip          inet,
  occurred_at timestamptz NOT NULL
);
CREATE INDEX events_customer_id ON events (customer_id);
